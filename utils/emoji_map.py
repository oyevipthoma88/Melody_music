def apply_aliases() -> int:
    """Point every alias glyph at its source glyph's verified id + chain."""
    applied = 0
    for alias, source in GLYPH_ALIASES.items():
        source_ids = EMOJI_ID_FALLBACKS.get(source) or (
            [EMOJI_ID_MAP[source]] if source in EMOJI_ID_MAP else []
        )
        if not source_ids:
            continue
        if alias not in EMOJI_ID_MAP:
            EMOJI_ID_MAP[alias] = source_ids[0]
        chain = EMOJI_ID_FALLBACKS.setdefault(alias, [])
        for emoji_id in source_ids:
            if emoji_id not in chain:
                chain.append(emoji_id)
        applied += 1
    return applied


