# ── Deep backup chain for EVERY glyph ─────────────────────────────────────
# REQUESTED ("all emojis ke backup me 10-15 ids add kr taki ek id work na hui
# to dusri karegi"): most glyphs only had 1-3 real ids, so a single rejected
# / expired document (400 DOCUMENT_INVALID) knocked that emoji straight back
# to plain unicode. Every glyph's chain is now topped up to MIN_FALLBACKS
# entries with other verified premium ids from the same harvested pack,
# picked deterministically from the glyph itself (same glyph -> same chain on
# every boot, no random flicker). emoji_patch quarantines a rejected id and
# retries with the next entry, so an emoji has 12 lives instead of one.
MIN_FALLBACKS = 12

import hashlib as _hl  # noqa: E402


def pad_fallbacks(pool=None, minimum: int = MIN_FALLBACKS) -> None:
    """Top every glyph's fallback chain up to `minimum` premium ids."""
    if pool is None:
        from utils.emoji_order_pack import ORDER_EMOJI_ID_POOL
        pool = list(ORDER_EMOJI_ID_POOL)
    pool = [str(i) for i in pool]
    if not pool:
        return
    for glyph, chain in EMOJI_ID_FALLBACKS.items():
        if len(chain) >= minimum:
            continue
        seen = set(chain)
        offset = int(_hl.sha256(glyph.encode("utf-8")).hexdigest(), 16) % len(pool)
        for step in range(len(pool)):
            if len(chain) >= minimum:
                break
            cand = pool[(offset + step) % len(pool)]
            if cand not in seen:
                seen.add(cand)
                chain.append(cand)


pad_fallbacks()

# Snapshot of the static chains — reused as extra backups after Telegram
# resolution rebuilds the map at startup.
_STATIC_FALLBACKS = {g: list(v) for g, v in EMOJI_ID_FALLBACKS.items()}



# ── Runtime resolution against Telegram ───────────────────────────────────
#
# BUG FIX ("premium emoji properly working nahi kar rahe"): the map above was
# assembled by hand, so a glyph was regularly paired with an id whose real
# artwork is a *different* emoji (❌ rendering as something unrelated), and
# ids that don't exist in the owner's packs silently degraded to plain text.
# On top of that, auto_premium_emoji() used to pick a RANDOM id from the pool
# for every glyph, so the same 🎵 became a different animation each message.
#
# The fix: ask Telegram itself. At startup we resolve the owner's full id
# pool (utils/emoji_ids.py) with get_custom_emoji_stickers(), which returns
# each id together with the standard emoji it depicts, and rebuild
# EMOJI_ID_MAP from that ground truth. Every glyph then maps to an id that
# really is that emoji, and the same glyph always animates the same way.

import logging as _logging

_log = _logging.getLogger(__name__)

# Ids the owner explicitly wants used for a specific glyph win over whatever
# Telegram reports first for that glyph (Telegram order is arbitrary when a
# pack has several variants of the same emoji).
_PREFERRED = dict(EMOJI_ID_MAP)

RESOLVED_IDS: set = set()


def _strip_vs(glyph: str) -> str:
    """Drop the U+FE0F 'emoji presentation' selector so '▶️' and '▶' key the
    same entry (the matcher re-adds an optional selector when wrapping)."""
    return glyph.replace("\ufe0f", "")


async def resolve_emoji_map(client) -> int:
    """Resolve the owner's whole premium-emoji id pool against Telegram and
    rebuild EMOJI_ID_MAP from the result. Returns how many glyphs are mapped.

    Safe to call once at startup right after `bot.start()`. Any failure is
    logged and swallowed — the hand-written map above stays in force, so
    premium emoji degrade to the previous behaviour instead of breaking.
    """
    from utils.emoji_ids import PREMIUM_EMOJI_ID_POOL

    resolved: dict = {}
    ok_ids: set = set()
    pool = [int(i) for i in (*PREMIUM_EMOJI_ID_POOL, *PLAY_CARD_EMOJI_IDS)]

    # Resolved via raw messages.GetCustomEmojiDocuments (batched at 200 ids
    # internally) — the high-level Sticker wrapper carries no custom_emoji_id.
    from utils.custom_emoji import EmojiResolutionUnavailable, resolve_custom_emoji

    try:
        pool_documents = await resolve_custom_emoji(client, pool)
    except EmojiResolutionUnavailable as exc:
        # Telegram cannot be asked (bot accounts may not call
        # messages.GetCustomEmojiDocuments). Keep the harvested static map —
        # every glyph stays premium, just without freshly verified artwork.
        _log.info("Premium emoji ids could not be verified (%s) — using static map.", exc)
        return len(EMOJI_ID_MAP)

    variants: dict[str, list[str]] = {}
    for emoji_id_int, alt in pool_documents.items():
        emoji_id = str(emoji_id_int)
        ok_ids.add(emoji_id)
        if not alt:
            continue
        glyph = _strip_vs(alt)
        variants.setdefault(glyph, []).append(emoji_id)
        preferred = _PREFERRED.get(glyph)
        if glyph not in resolved or emoji_id == preferred:
            resolved[glyph] = emoji_id

    if not resolved:
        _log.warning("Premium emoji resolution returned nothing — keeping static map.")
        return len(EMOJI_ID_MAP)

    # Keep hand-mapped glyphs Telegram didn't return (decorative ones such as
    # ✵ / ♛ that the packs label with a different base emoji).
    for glyph, emoji_id in _PREFERRED.items():
        resolved.setdefault(glyph, emoji_id)

    EMOJI_ID_MAP.clear()
    EMOJI_ID_MAP.update(resolved)
    EMOJI_ID_FALLBACKS.clear()
    for glyph, primary in resolved.items():
        choices = [primary, *(variants.get(glyph) or [])]
        # Keep the static (harvested) chain as extra backups behind the
        # freshly verified ones, then top up to MIN_FALLBACKS from the pool
        # of ids Telegram just confirmed as valid.
        choices += _STATIC_FALLBACKS.get(glyph, [])
        EMOJI_ID_FALLBACKS[glyph] = list(dict.fromkeys(str(c) for c in choices))
    apply_aliases()
    pad_fallbacks(sorted(ok_ids))
    RESOLVED_IDS.clear()
    RESOLVED_IDS.update(ok_ids)


    from utils.telegram_html import refresh_glyph_pattern

    refresh_glyph_pattern()
    _log.info(
        "🎞️ Premium emoji ready: %d/%d ids valid, %d glyphs mapped.",
        len(ok_ids), len(pool), len(EMOJI_ID_MAP),
    )
    return len(EMOJI_ID_MAP)



# ── Auto-premium for every remaining glyph ────────────────────────────────
#
# REQUESTED ("jitne bhi non premium emojis hai unko random emoji id add kr
# do"): a glyph that no id in the pack actually depicts used to stay a plain
# unicode emoji forever. Now any such glyph is given an id from the owner's
# own verified pool, picked pseudo-randomly but *deterministically* from the
# glyph itself — so it is premium/animated everywhere, and the SAME glyph
# always keeps the SAME animation instead of changing per message.


AUTO_ASSIGNED_IDS: dict = {}

# Glyphs no pack depicts — kept plain instead of animating the wrong emoji.
UNMATCHED_GLYPHS: set = set()


# BUG FIX (Heroku log: "emoji_patch: Telegram rejected custom-emoji entities
# ([400 ENTITY_TEXT_INVALID]) — strike 1/8"):
#
# Auto-assignment happily handed a premium id to glyphs that Telegram does
# NOT accept as the text of a custom_emoji entity — seen in the log right
# before the rejection: '🇩' (a lone regional indicator), '❜', '✘', '♥',
# '🕊' (text-presentation dingbats/symbols). One such entity makes Telegram
# reject the WHOLE message, and eight of those disabled premium emoji for
# the entire process. Only glyphs that are real, standalone emoji
# (Emoji_Presentation, or explicitly written with U+FE0F) may be wrapped.

def _entity_safe(raw_glyph: str) -> bool:
    """True when Telegram will accept `raw_glyph` inside a custom-emoji entity."""
    if not raw_glyph:
        return False
    # Keyword / flag sequences and ZWJ sequences are fine as written.
    if "\u200d" in raw_glyph or "\ufe0f" in raw_glyph:
        return True
    cps = [ord(c) for c in raw_glyph if c not in ("\ufe0f", "\u200d")]
    if not cps:
        return False
    # A complete flag is two regional indicators — always a valid emoji.
    if len(cps) == 2 and all(0x1F1E6 <= cp <= 0x1F1FF for cp in cps):
        return True
    # A lone regional indicator ('🇩') is half a flag — never a valid emoji.
    if any(0x1F1E6 <= cp <= 0x1F1FF for cp in cps) and len(cps) == 1:
        return False
    # Skin-tone modifiers / keycaps only make sense attached to a base.
    if len(cps) == 1 and (0x1F3FB <= cps[0] <= 0x1F3FF or cps[0] == 0x20E3):
        return False
    # Default emoji-presentation blocks. Anything outside them (dingbats such
    # as ❜ ✘ ♥ ✵ ♛, arrows, text symbols) needs U+FE0F to render as emoji and
    # is rejected by Telegram without it.
    ranges = (
        (0x1F300, 0x1F5FF), (0x1F600, 0x1F64F), (0x1F680, 0x1F6FF),
        (0x1F700, 0x1F77F), (0x1F900, 0x1F9FF), (0x1FA70, 0x1FAFF),
        (0x1F004, 0x1F004), (0x1F0CF, 0x1F0CF), (0x1F18E, 0x1F18E),
        (0x1F191, 0x1F19A), (0x1F201, 0x1F202), (0x1F232, 0x1F23A),
        (0x2705, 0x2705), (0x270A, 0x270B), (0x2728, 0x2728),
        (0x274C, 0x274C), (0x274E, 0x274E), (0x2753, 0x2755),
        (0x2757, 0x2757), (0x2795, 0x2797), (0x27B0, 0x27B0),
        (0x27BF, 0x27BF), (0x2B1B, 0x2B1C), (0x2B50, 0x2B50),
        (0x2B55, 0x2B55),
    )
    # Default *text*-presentation codepoints inside those blocks (🕊 ⛱ 🖥 …).
    # Without U+FE0F Telegram treats them as text, not emoji, and rejects the
    # entity — '🕊' is exactly what triggered ENTITY_TEXT_INVALID in the log.
    text_default = (
        (0x1F321, 0x1F32C), (0x1F336, 0x1F336), (0x1F37D, 0x1F37D),
        (0x1F396, 0x1F397), (0x1F399, 0x1F39B), (0x1F39E, 0x1F39F),
        (0x1F3CB, 0x1F3CE), (0x1F3D4, 0x1F3DF), (0x1F3F3, 0x1F3F3),
        (0x1F3F5, 0x1F3F5), (0x1F3F7, 0x1F3F7), (0x1F43F, 0x1F43F),
        (0x1F441, 0x1F441), (0x1F4FD, 0x1F4FD), (0x1F549, 0x1F54A),
        (0x1F56F, 0x1F570), (0x1F573, 0x1F579), (0x1F587, 0x1F587),
        (0x1F58A, 0x1F58D), (0x1F590, 0x1F590), (0x1F5A5, 0x1F5A5),
        (0x1F5A8, 0x1F5A8), (0x1F5B1, 0x1F5B2), (0x1F5BC, 0x1F5BC),
        (0x1F5C2, 0x1F5C4), (0x1F5D1, 0x1F5D3), (0x1F5DC, 0x1F5DE),
        (0x1F5E1, 0x1F5E1), (0x1F5E3, 0x1F5E3), (0x1F5E8, 0x1F5E8),
        (0x1F5EF, 0x1F5EF), (0x1F5F3, 0x1F5F3), (0x1F5FA, 0x1F5FA),
        (0x1F6CB, 0x1F6CB), (0x1F6CD, 0x1F6CF), (0x1F6E0, 0x1F6E5),
        (0x1F6E9, 0x1F6E9), (0x1F6F0, 0x1F6F0), (0x1F6F3, 0x1F6F3),
    )
    if any(any(lo <= cp <= hi for lo, hi in text_default) for cp in cps):
        return False
    return all(any(lo <= cp <= hi for lo, hi in ranges) for cp in cps)


UNSAFE_GLYPHS: set = set()


def entity_text(glyph: str) -> "str | None":
    """The exact text Telegram will accept inside a custom-emoji entity.

    ROOT FIX for "kuch emojis abhi bhi normal me ja rahe hai": a
    text-presentation symbol (🕊 ⛱ ✍ ❤ ⚠) is rejected as an entity when it is
    written WITHOUT U+FE0F, so those glyphs always fell back to plain text.
    Instead of giving up we now re-emit the very same glyph WITH the emoji
    presentation selector, which Telegram accepts — so it renders premium.
    """
    if not glyph:
        return None
    base = _strip_vs(glyph)
    cps = [ord(c) for c in base if c != "\u200d"]
    # Degenerate fragments stay plain even WITH U+FE0F: Telegram answers
    # ENTITY_TEXT_INVALID for a lone regional indicator / skin tone / keycap
    # combining mark, and one bad entity kills the whole message.
    if len(cps) == 1 and (
        0x1F1E6 <= cps[0] <= 0x1F1FF
        or 0x1F3FB <= cps[0] <= 0x1F3FF
        or cps[0] == 0x20E3
    ):
        return None
    for candidate in (glyph, base, base + "\ufe0f"):
        if candidate and _entity_safe(candidate):
            return candidate
    return None


def assign_pool_id(glyph: str) -> "str | None":
    """Return (creating if needed) a premium id for `glyph`.

    `glyph` may be a full emoji sequence (ZWJ family, flag, keycap,
    skin-toned emoji), not just a single codepoint.
    """
    raw = glyph or ""
    glyph = _strip_vs(raw)
    if not glyph:
        return None
    if entity_text(raw) is None:
        # Telegram would reject it as an entity — leave it as plain unicode
        # instead of poisoning the whole message.
        if glyph not in UNSAFE_GLYPHS:
            UNSAFE_GLYPHS.add(glyph)
            _log.debug("premium emoji: %r is not a valid custom-emoji target", glyph)
        return None
    # 🌍 Universal coverage: ask Telegram (in the background) for a premium
    # emoji that really depicts THIS glyph, so any emoji in the world — even
    # one added to the code tomorrow — ends up premium instead of plain.
    try:
        from utils import emoji_search

        looked_up = emoji_search.cached_id(glyph)
        if looked_up and str(looked_up) not in _dead_ids():
            return str(looked_up)
        emoji_search.request(glyph)
    except Exception:
        pass

    mapped = EMOJI_ID_MAP.get(glyph)
    if mapped and str(mapped) not in _dead_ids():
        return str(mapped)
    cached = AUTO_ASSIGNED_IDS.get(glyph)
    if cached and cached not in _dead_ids():
        return cached

    # ── ACCURACY GATE ─────────────────────────────────────────────────
    # REQUESTED ("perfect premium emoji id"): earlier this point handed the
    # glyph a RANDOM id from the owner's pool, which animated as a completely
    # different emoji (🧾 as a football, ⚖ as a cake…). A wrong animation is
    # worse than a plain glyph, so an unmatched glyph now stays plain unicode
    # and is recorded in UNMATCHED_GLYPHS for the owner to map (see
    # GLYPH_ALIASES above and tools/verify_card_emojis.py).
    # Skin-toned emoji (🙋🏻) borrow the id of their toneless base (🙋 → 👋).
    base = glyph.rstrip("\U0001F3FB\U0001F3FC\U0001F3FD\U0001F3FE\U0001F3FF")
    alias = GLYPH_ALIASES.get(glyph) or (
        base if base != glyph and base in EMOJI_ID_MAP else None
    ) or GLYPH_ALIASES.get(base)
    if alias:
        alias_id = EMOJI_ID_MAP.get(alias)
        if alias_id and str(alias_id) not in _dead_ids():
            AUTO_ASSIGNED_IDS[glyph] = str(alias_id)
            EMOJI_ID_MAP[glyph] = str(alias_id)
            EMOJI_ID_FALLBACKS.setdefault(glyph, []).append(str(alias_id))
            try:
                from utils.telegram_html import refresh_glyph_pattern
                refresh_glyph_pattern()
            except Exception:
                pass
            return str(alias_id)

    if glyph not in UNMATCHED_GLYPHS:
        UNMATCHED_GLYPHS.add(glyph)
        _log.info(
            "premium emoji: no id in the packs depicts %r — kept as plain "
            "unicode (add it to GLYPH_ALIASES / utils/emoji_ids.py).", glyph,
        )
    return None


def _dead_ids() -> set:
    """Ids Telegram concretely rejected at runtime — never reuse them."""
    try:
        from utils.emoji_patch import QUARANTINED_IDS
        return {str(i) for i in QUARANTINED_IDS}
    except Exception:
        return set()
